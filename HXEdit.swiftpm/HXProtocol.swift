import Foundation

/// Reverse-engineered byte sequences for the Line 6 HX proprietary protocol.
///
/// IMPORTANT: These packets are transported over **USB bulk transfers** on the
/// device's vendor-specific interface (VID `0x0E41` / PID `0x4253`, interface 0,
/// EP OUT `0x01`, EP IN `0x81`). They are NOT MIDI SysEx and cannot be sent
/// through CoreMIDI. See `Reference/docs/protocol/` for full specification.
enum HXProtocol {

    // MARK: - USB Identification

    static let vendorID: UInt16  = 0x0E41
    static let productID: UInt16 = 0x4253
    static let interfaceNumber   = 0
    static let endpointOut: UInt8 = 0x01
    static let endpointIn: UInt8  = 0x81

    // MARK: - Transport Constants

    static let readBufferSize    = 512
    static let operationTimeoutMs = 2000
    static let drainTimeoutMs    = 50
    static let maxChunkSize      = 272

    // MARK: - Session Handshake (5-packet init, see session-handshake.md)

    /// Packet 1 — HANDSHAKE. Magic value `0x0028`.
    static let handshake = Data([
        0x0C, 0x00, 0x00, 0x28, 0x01, 0x10, 0xEF, 0x03,
        0x00, 0x00, 0x00, 0x02, 0x00, 0x01, 0x00, 0x21,
        0x00, 0x10, 0x00, 0x00
    ])

    /// Packet 2 — SESSION_OPEN_1 (`cmd=0x04`, `seq=0x02`).
    static let sessionOpen1 = Data([
        0x11, 0x00, 0x00, 0x18, 0x01, 0x10, 0xEF, 0x03,
        0x00, 0x02, 0x00, 0x04, 0x00, 0x10, 0x00, 0x00,
        0x01, 0x00, 0x02, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x02, 0x00, 0x00, 0x00
    ])

    /// Packet 3 — SESSION_CHUNK_1 (`cmd=0x08`, `seq=0x03`).
    static let sessionChunk1 = Data([
        0x08, 0x00, 0x00, 0x18, 0x01, 0x10, 0xEF, 0x03,
        0x00, 0x03, 0x00, 0x08, 0x09, 0x10, 0x00, 0x00
    ])

    /// Packet 4 — SESSION_OPEN_2 (`cmd=0x04`, `seq=0x04`).
    static let sessionOpen2 = Data([
        0x1A, 0x00, 0x00, 0x18, 0x01, 0x10, 0xEF, 0x03,
        0x00, 0x04, 0x00, 0x04, 0x09, 0x10, 0x00, 0x00,
        0x01, 0x00, 0x02, 0x00, 0x0A, 0x00, 0x00, 0x00,
        0x83, 0x66, 0xCD, 0x03, 0xE8, 0x64, 0xCC, 0xFE,
        0x65, 0x80, 0x00, 0x00
    ])

    /// Packet 5 — SESSION_CHUNK_2 (`cmd=0x08`, `seq=0x05`).
    static let sessionChunk2 = Data([
        0x08, 0x00, 0x00, 0x18, 0x01, 0x10, 0xEF, 0x03,
        0x00, 0x05, 0x00, 0x08, 0x1A, 0x10, 0x00, 0x00
    ])

    /// Ordered handshake sequence. Send each, read one response (discard), continue.
    /// Next available sequence number after handshake is `0x06`.
    static let handshakeSequence: [Data] = [
        handshake, sessionOpen1, sessionChunk1, sessionOpen2, sessionChunk2
    ]

    // MARK: - Preset Operations (see presets/list.md)

    /// Phase 1 — OPEN_PRESETS (`cmd=0x04`, `seq=0x06`).
    /// Instructs the device to prepare the preset resource for streaming.
    static let openPresets = Data([
        0x19, 0x00, 0x00, 0x18, 0x01, 0x10, 0xEF, 0x03,
        0x00, 0x06, 0x00, 0x04, 0x1A, 0x10, 0x00, 0x00,
        0x01, 0x00, 0x02, 0x00, 0x09, 0x00, 0x00, 0x00,
        0x83, 0x66, 0xCD, 0x03, 0xE9, 0x64, 0x00, 0x65,
        0xC0, 0x00, 0x00, 0x00
    ])

    /// Phase 2 — OPEN_STREAM (`cmd=0x0C`, `seq=0x07`). Begins paged preset stream.
    static let openStream = Data([
        0x1D, 0x00, 0x00, 0x18, 0x01, 0x10, 0xEF, 0x03,
        0x00, 0x07, 0x00, 0x0C, 0x38, 0x10, 0x00, 0x00,
        0x01, 0x00, 0x02, 0x00, 0x0D, 0x00, 0x00, 0x00,
        0x83, 0x66, 0xCD, 0x03, 0xEA, 0x64, 0x01, 0x65,
        0x82, 0x6B, 0x00, 0x65, 0x02, 0x00, 0x00, 0x00
    ])

    static let chunkStreamStartOffset: UInt32 = 0x0000_1138
    static let chunkStreamSeqStart: UInt8 = 0x08
    static let chunkStreamOffsetStep: UInt32 = 0x0100

    /// Phase 3 — Paged chunk request. Sequence increments per call, offset by `0x0100`.
    static func chunkRequest(seq: UInt8, offset: UInt32) -> Data {
        let o = offset.littleEndianBytes
        return Data([
            0x08, 0x00, 0x00, 0x18, 0x01, 0x10, 0xEF, 0x03,
            0x00, seq,  0x00, 0x08, o.0,  o.1,  o.2,  o.3
        ])
    }

    /// 3-byte marker that locates the MessagePack `array16(128)` in the reassembled
    /// chunk stream. After locating this, parse from `start_index` onward.
    static let presetArrayMarker = Data([0xDC, 0x00, 0x80])

    /// Inner-map key holding the preset name string (null-terminated by the device).
    static let presetNameKey = 109
}

private extension UInt32 {
    var littleEndianBytes: (UInt8, UInt8, UInt8, UInt8) {
        (UInt8(self & 0xFF),
         UInt8((self >> 8)  & 0xFF),
         UInt8((self >> 16) & 0xFF),
         UInt8((self >> 24) & 0xFF))
    }
}
